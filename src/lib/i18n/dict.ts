export type Key = keyof typeof dict

export const tr = (lang: Lang, k: Key, vars?: Record<string, string | number>) => {
  let s: string = dict[k] ? dict[k][lang === 'ar' ? 0 : 1] : String(k)
  if (vars) {
    for (const v in vars) {
      s = s.replace('{' + v + '}', String(vars[v]))
    }
  }
  return s
}

